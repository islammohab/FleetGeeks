String splitWords(String symbol) =>
    symbol.replaceAllMapped(RegExp('([a-z])([A-Z])'), (m) => '${m[1]} ${m[2]}').replaceAllMapped(RegExp('([A-Z]+)([A-Z][a-z])'), (m) => '${m[1]} ${m[2]}');

class Strings {
  const Strings(this.lang);
  final String lang;

  bool get rtl => lang == 'ar';

  String t(String key, [List<Object?> args = const []]) {
    var text = (lang == 'ar' ? ar[key] : null) ?? en[key] ?? key;
    for (var i = 0; i < args.length; i++) {
      text = text.replaceAll('{$i}', '${args[i] ?? ''}');
    }
    return text;
  }

  String status(String symbol) => lang == 'ar' ? (statusAr[symbol] ?? splitWords(symbol)) : splitWords(symbol);
}

const _langKey = 'fg.lang';

class LocaleNotifier extends Notifier<Locale> {
  @override
  Locale build() {
    ref.read(secureStorageProvider).read(key: _langKey).then((v) {
      if (v == 'ar' || v == 'en') state = Locale(v!);
    });
    return Locale(WidgetsBinding.instance.platformDispatcher.locale.languageCode == 'ar' ? 'ar' : 'en');
  }

  void toggle() {
    state = Locale(state.languageCode == 'ar' ? 'en' : 'ar');
    ref.read(secureStorageProvider).write(key: _langKey, value: state.languageCode);
  }
}

final localeProvider = NotifierProvider<LocaleNotifier, Locale>(LocaleNotifier.new);
final stringsProvider = Provider<Strings>((ref) => Strings(ref.watch(localeProvider).languageCode));
